func newCode() string {
	const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789" // no 0/O/1/I, easy to type on a phone
	b := make([]byte, 12)                               // 60 bits: far too many to guess, even offline
	rand.Read(b)
	for i := range b {
		b[i] = alphabet[int(b[i])%len(alphabet)]
	}
	return string(b)
}

func newID() string { b := make([]byte, 8); rand.Read(b); return hex.EncodeToString(b) }

func loadConfig() {
	dir, err := os.UserConfigDir()
	if err != nil {
		dir = "."
	}
	if p := os.Getenv("PCPOWER_CONFIG"); p != "" {
		cfgPath = p
	} else {
		cfgPath = filepath.Join(dir, "PCPower", "config.json")
	}
	if b, err := os.ReadFile(cfgPath); err == nil {
		json.Unmarshal(b, &cfg)
	}
	if len(cfg.Token) != 12 { // also replaces the short codes of versions before 2.0
		cfg.Token = newCode()
	}
	if cfg.LocalPort == 0 {
		cfg.LocalPort = 8786
	}
	if cfg.LanOnly == nil {
		t := true
		cfg.LanOnly = &t
	}
	if cfg.Devices == nil {
		cfg.Devices = []Device{}
	}
	if cfg.Name == "" {
		cfg.Name, _ = os.Hostname()
	}
	if cfg.Port == 0 {
		cfg.Port = 8787
	}
	if cfg.Schedules == nil {
		cfg.Schedules = []Schedule{}
	}
	saveConfig()
}

// saveConfig must be called with mu held (or before the server starts).
func saveConfig() {
	os.MkdirAll(filepath.Dir(cfgPath), 0o700)
	b, _ := json.MarshalIndent(cfg, "", "  ")
	tmp := cfgPath + ".tmp"
	if os.WriteFile(tmp, b, 0o600) == nil {
		os.Rename(tmp, cfgPath)
	}
}

// netInfo reports the network card this PC uses to reach the network: the one the phone must wake.
func netInfo() (ip, mac, broadcast string) {
	want := ""
	if c, err := net.Dial("udp4", "192.0.2.1:9"); err == nil { // no packet is sent; this only asks the OS for the route
		want = c.LocalAddr().(*net.UDPAddr).IP.String()
		c.Close()
	}
	ifaces, _ := net.Interfaces()
	for pass := 0; pass < 2; pass++ {
		for _, ifc := range ifaces {
			if ifc.Flags&net.FlagUp == 0 || ifc.Flags&net.FlagLoopback != 0 || len(ifc.HardwareAddr) != 6 {
				continue
			}
			addrs, _ := ifc.Addrs()
			for _, a := range addrs {
				n, ok := a.(*net.IPNet)
				v4 := n.IP.To4()
				if !ok || v4 == nil || (pass == 0 && v4.String() != want) {
					continue
				}
				bc := make(net.IP, 4)
				for i := range bc {
					bc[i] = v4[i] | ^n.Mask[len(n.Mask)-4+i]
				}
				return v4.String(), ifc.HardwareAddr.String(), bc.String()
			}
		}
	}
	return "", "", ""
}

// WolAdapter is one network card's wake settings as Windows reports them.
type WolAdapter struct {
	Name    string `json:"name"`
	Magic   string `json:"magic"`   // Enabled / Disabled / Unsupported
	Pattern string `json:"pattern"` // Enabled means ordinary traffic can wake the PC
	Wifi    bool   `json:"wifi"`
	Active  bool   `json:"active"` // the card this PC is using right now
}

type WolReport struct {
	Supported   bool         `json:"supported"`
	Adapters    []WolAdapter `json:"adapters"`
	FastStartup bool         `json:"fastStartup"`
	WakeTimers  string       `json:"wakeTimers"` // Windows "Allow wake timers": Enabled, Disabled, ImportantOnly or ""
	Connection  string       `json:"connection"` // "wifi", "ethernet" or "" when unknown
	Error       string       `json:"error,omitempty"`
}

var (
	wolMu    sync.Mutex
	wolCache *WolReport
	wolAt    time.Time
)

func wolCheck(fresh bool) WolReport {
	wolMu.Lock()
	defer wolMu.Unlock()
	if wolCache == nil || fresh || time.Since(wolAt) > 60*time.Second {
		r := wolRead()
		wolCache, wolAt = &r, time.Now()
	}
	return *wolCache
}

var (
	pending   *pendingT // guarded by mu: the shutdown or restart that is counting down, if any
	labels    = map[string]string{"shutdown": "Shut down", "restart": "Restart", "sleep": "Sleep", "hibernate": "Hibernate", "wake": "Turn on"}
	priority  = map[string]int{"shutdown": 4, "restart": 3, "hibernate": 2, "sleep": 1}
	countdown = 60 * time.Second
)

type pendingT struct {
	Action string
	At     time.Time
}

// pendingNow must be called with mu held.
func pendingNow() *pendingT {
	if pending != nil && time.Now().After(pending.At) {
		pending = nil
	}
	return pending
}

func execPower(action string) error {
	log.Printf("power: %s (dry run: %v)", action, dryRun)
	if dryRun {
		return nil
	}
	return doPower(action)
}

// requestPower is the single place every power request goes through (PC window, phone, schedules),
// so two requests can never fight each other. Rules:
//   - the same action twice: the countdown carries on, it does not restart
//   - a different action from a person: replaces the one counting down
//   - a schedule never replaces a countdown that is already running
//   - sleep/hibernate first cancel a countdown, so it cannot fire when the PC wakes up
func requestPower(action string, manual bool) (string, error) {
	mu.Lock()
	defer mu.Unlock()
	p := pendingNow()
	if action == "cancel" {
		execPower("cancel") // also clears a countdown started outside PC Power
		pending = nil
		if p == nil {
			return "Nothing was counting down.", nil
		}
		return labels[p.Action] + " cancelled.", nil
	}
	if action == "hibernate" && !canHibernate() {
		return "", errors.New("Hibernate is turned off on this PC. Use Sleep or Shut down instead.")
	}
	if p != nil && p.Action == action {
		return fmt.Sprintf("%s is already counting down (%d seconds left).", labels[action], int(time.Until(p.At).Seconds())+1), nil
	}
	prefix := ""
	if p != nil {
		if !manual {
			log.Printf("schedule %s skipped: %s is already counting down", action, p.Action)
			return "skipped", nil
		}
		execPower("cancel")
		pending = nil
		prefix = labels[p.Action] + " cancelled. "
	}
	if action == "sleep" || action == "hibernate" {
		go func() {
			time.Sleep(800 * time.Millisecond) // let the reply reach the phone first
			if err := execPower(action); err != nil {
				log.Printf("power %s failed: %v", action, err)
			}
		}()
		return prefix + labels[action] + " now.", nil
	}
	if err := execPower(action); err != nil {
		log.Printf("power %s failed: %v", action, err)
		return "", errors.New("Windows already has a shutdown or restart waiting. Press Cancel countdown, then try again.")
	}
	pending = &pendingT{action, time.Now().Add(countdown)}
	return prefix + labels[action] + " in 60 seconds. Press Cancel to stop it.", nil
}

// Schedules run from this PC's own clock. One missed while the PC was off is skipped, never run late.
func scheduler() {
	for ; ; time.Sleep(10 * time.Second) {
		now := time.Now()
		date, hm := now.Format("2006-01-02"), now.Format("15:04")
		key := date + " " + hm
		var fire []string
		mu.Lock()
		for i := range cfg.Schedules {
			s := &cfg.Schedules[i]
			if !s.Enabled || s.Action == "wake" || s.Time != hm || s.LastFired == key {
				continue // turn-on schedules are handled by wakeLoop, with a hardware wake timer
			}
			if len(s.Days) > 0 {
				ok := false
				for _, d := range s.Days {
					ok = ok || d == int(now.Weekday())
				}
				if !ok {
					continue
				}
			} else if s.Date != date {
				continue
			}
			s.LastFired = key
			if len(s.Days) == 0 {
				s.Enabled = false
			}
			fire = append(fire, s.Action)
		}
		if len(fire) > 0 {
			saveConfig()
		}
		mu.Unlock()
		best := ""
		for _, a := range fire {
			if priority[a] > priority[best] {
				best = a
			}
		}
		if best != "" {
			log.Printf("schedule fired: %s at %s (of %v)", best, key, fire)
			requestPower(best, false)
		}
	}
}

func discovery() {
	conn, err := net.ListenUDP("udp4", &net.UDPAddr{Port: discoveryPort})
	if err != nil {
		log.Printf("discovery disabled: %v", err)
		return
	}
	buf := make([]byte, 256)
	for {
		n, addr, err := conn.ReadFromUDP(buf)
		if err != nil {
			return
		}
		if strings.TrimSpace(string(buf[:n])) != "PCPOWER_DISCOVER" {
			continue
		}
		mu.Lock()
		reply, _ := json.Marshal(map[string]any{"app": "pcpower", "name": cfg.Name, "port": cfg.Port})
		mu.Unlock()
		conn.WriteToUDP(reply, addr)
	}
}

// sameDay reports whether two schedules can fall on the same day.
func sameDay(a, b Schedule) bool {
	days := func(s Schedule) map[int]bool {
		m := map[int]bool{}
		for _, d := range s.Days {
			m[d] = true
		}
		if len(s.Days) == 0 {
			if t, err := time.Parse("2006-01-02", s.Date); err == nil {
				m[int(t.Weekday())] = true
			}
		}
		return m
	}
	if len(a.Days) == 0 && len(b.Days) == 0 {
		return a.Date == b.Date
	}
	da, db := days(a), days(b)
	for d := range da {
		if db[d] {
			return true
		}
	}
	return false
}

// ---- scheduled turn-on ----
//
// A PC that is asleep or hibernating can wake itself: Windows programs the motherboard clock to power it
// up at a set time. That is what a "Turn on" schedule uses, so no other device is needed. It cannot work
// after a full shut down, because then Windows is not there to have set the clock.

var wakeKick = make(chan struct{}, 1)

// kickWake tells wakeLoop the schedules changed.
func kickWake() {
	select {
	case wakeKick <- struct{}{}:
	default:
	}
}

// nextOccurrence returns when s next falls due after now (zero if never).
func nextOccurrence(s Schedule, now time.Time) time.Time {
	hm, err := time.ParseInLocation("15:04", s.Time, now.Location())
	if err != nil {
		return time.Time{}
	}
	at := func(day time.Time) time.Time {
		return time.Date(day.Year(), day.Month(), day.Day(), hm.Hour(), hm.Minute(), 0, 0, now.Location())
	}
	if len(s.Days) == 0 {
		d, err := time.ParseInLocation("2006-01-02", s.Date, now.Location())
		if err != nil || !at(d).After(now) {
			return time.Time{}
		}
		return at(d)
	}
	for i := 0; i <= 7; i++ {
		day := now.AddDate(0, 0, i)
		for _, wd := range s.Days {
			if wd == int(day.Weekday()) && at(day).After(now) {
				return at(day)
			}
		}
	}
	return time.Time{}
}

// nextWake finds the soonest enabled turn-on schedule. Must be called with mu held.
func nextWake(now time.Time) time.Time {
	var best time.Time
	for _, s := range cfg.Schedules {
		if !s.Enabled || s.Action != "wake" {
			continue
		}
		if t := nextOccurrence(s, now); !t.IsZero() && (best.IsZero() || t.Before(best)) {
			best = t
		}
	}
	return best
}

var wakeState struct {
	sync.Mutex
	next time.Time
	err  string
}

func wakeLoop() {
	fired := wakeInit()
	tick := time.NewTicker(10 * time.Minute) // also re-arms after clock changes
	for {
		now := time.Now()
		mu.Lock()
		next := nextWake(now)
		mu.Unlock()
		err := wakeArm(next)
		wakeState.Lock()
		wakeState.next, wakeState.err = next, ""
		if err != nil {
			wakeState.err = err.Error()
			log.Printf("cannot set the turn-on timer: %v", err)
		}
		wakeState.Unlock()
		select {
		case <-wakeKick:
		case <-tick.C:
		case <-fired:
			now = time.Now()
			key := now.Format("2006-01-02 15:04")
			mu.Lock()
			for i := range cfg.Schedules {
				s := &cfg.Schedules[i]
				// Due in the last two minutes (the PC needs a moment to come up).
				if s.Enabled && s.Action == "wake" {
					if t := nextOccurrence(*s, now.Add(-2*time.Minute)); !t.IsZero() && !t.After(now) {
						s.LastFired = key
						if len(s.Days) == 0 {
							s.Enabled = false
						}
					}
				}
			}
			saveConfig()
			mu.Unlock()
			log.Printf("scheduled turn-on at %s", key)
			wakeKeepOn(30 * time.Minute)
		}
	}
}

func wakeInfo() map[string]any {
	wakeState.Lock()
	defer wakeState.Unlock()
	out := map[string]any{"supported": wakeSupported, "error": wakeState.err}
	if !wakeState.next.IsZero() {
		out["next"] = wakeState.next.Format("2006-01-02 15:04")
	}
	return out
}
